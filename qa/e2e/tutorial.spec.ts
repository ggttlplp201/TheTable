import { test, expect } from './fixtures';
import type { Page } from '@playwright/test';
const step = (page: Page, name: string) => expect(page.locator('.tutorial-shell')).toHaveAttribute('data-step', name, { timeout:20_000 });
const next = (page: Page) => page.getByRole('button', { name: 'CONTINUE →', exact: true }).click();

test('fresh tutorial is optional and can be opened from the menu', async ({ page }) => {
  await page.goto('/');
  await expect(page.getByRole('dialog', { name: 'New to The Table?' })).toBeVisible();
  await page.getByRole('button', { name: 'SKIP FOR NOW' }).click();
  await expect(page.getByRole('dialog', { name: 'New to The Table?' })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('button', { name: 'TUTORIAL', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'TUTORIAL', exact: true }).click();
  await step(page, 'look');
});

test('all six chapters use production controls, persist completion, and replay', async ({ page }) => {
  test.setTimeout(240_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'PLAY TUTORIAL', exact: true }).click();
  await step(page, 'look');
  const canvas = page.locator('.table-presentation-canvas canvas');
  await expect(canvas).toBeVisible();
  for (let i = 0; i < 3 && await page.locator('.tutorial-shell').getAttribute('data-step') === 'look'; i++) {
    await page.mouse.move(500, 500); await page.mouse.down();
    await page.mouse.move(950, 500, { steps: 20 }); await page.waitForTimeout(400); await page.mouse.move(400, 500, { steps: 25 }); await page.mouse.up();
  }
  await step(page, 'dealer');
  await next(page); await step(page, 'inventory'); await next(page); await step(page, 'pocket');
  await page.getByRole('button', { name: 'Pockets', exact: true }).click();
  await page.getByRole('button', { name: 'Medicine', exact: true }).click();
  await page.getByRole('button', { name: 'PLACE IN POCKET', exact: true }).click();
  await step(page, 'privacy');
  await next(page); await step(page, 'trade');
  await page.getByRole('button', { name: '[1] ⇄ Trade', exact: true }).click();
  await page.getByRole('button', { name: 'Propose Trade', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Give your Key');
  await step(page, 'trade');
  await page.getByRole('checkbox', { name: /Key/ }).check();
  await page.getByLabel('You request Gold', { exact: true }).fill('2');
  await page.getByRole('button', { name: 'Propose Trade', exact: true }).click();
  await step(page, 'reward');
  await expect(page.locator('.self-vitals')).toContainText('9');
  await next(page); await step(page, 'refuse');
  await page.getByRole('button', { name: 'Refuse', exact: true }).click();
  await step(page, 'bluff'); await next(page); await step(page, 'practice');
  await page.getByRole('button', { name: '[2] ⚠ Threaten', exact: true }).click();
  await page.getByRole('button', { name: /^Under cloth/i }).click();
  await page.getByRole('button', { name: 'Knife', exact: true }).click();
  await page.getByLabel('You demand Gold', { exact: true }).fill('1');
  await page.getByRole('button', { name: 'Make Threat', exact: true }).click();
  await step(page, 'practiceDone'); await next(page);
  await step(page, 'downed');
  await expect(page.getByRole('button', { name: 'Chat', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /REVIVE WITH MEDICINE/ }).click();
  await step(page, 'income'); await next(page); await step(page, 'publicShop');
  await page.screenshot({ path: 'audit/screenshots/tutorial-public-shop.png' });
  await expect(page.getByRole('button', { name: 'Black Market', exact: true }).last()).toBeDisabled();
  await page.getByRole('button', { name: 'Buy Key', exact: true }).click();
  await step(page, 'blackMarket');
  await page.getByRole('button', { name: 'Black Market', exact: true }).last().click();
  await page.getByRole('button', { name: 'Buy Antidote', exact: true }).click();
  await step(page, 'finishShopping');
  await page.getByRole('button', { name: 'Finish Intermission', exact: true }).click();
  await step(page, 'chest');
  await page.screenshot({ path:'audit/screenshots/tutorial-chest.png' });
  const chest = await page.locator('.table-presentation').evaluate(element => { const style = getComputedStyle(element); return { x:parseFloat(style.getPropertyValue('--scene-standard-x')), y:parseFloat(style.getPropertyValue('--scene-standard-y')) + 40 }; });
  await page.mouse.click(chest.x,chest.y);
  await page.getByRole('button', { name: 'YES, OPEN', exact: true }).click();
  await step(page, 'objective');
  await expect(page.getByRole('button', { name: '⤴ LEAVE TABLE', exact: true })).toHaveCount(0);
  await next(page); await step(page, 'draw');
  await page.locator('.action-dock').hover();
  await page.getByRole('button', { name: '✦ Draw Wildcard', exact: true }).click();
  await page.getByRole('button', { name: 'DRAW WILDCARD', exact: true }).click();
  await step(page, 'use');
  await expect(page.getByRole('dialog', { name:'Private Wildcard decision' })).toBeVisible();
  await page.getByRole('button', { name:'BURN', exact:true }).click();
  await step(page, 'draw');
  await page.locator('.action-dock').hover();
  await page.getByRole('button', { name: '✦ Draw Wildcard', exact: true }).click();
  await page.getByRole('button', { name: 'DRAW WILDCARD', exact: true }).click();
  await step(page, 'use');
  await page.getByRole('button', { name:'USE', exact:true }).click();
  await step(page, 'seize');
  await page.getByLabel('Wildcard target player').selectOption('dealer');
  await page.getByLabel('Wildcard target item').selectOption({ label:'Pistol' });
  await page.getByRole('button', { name:'RESOLVE WILDCARD', exact:true }).click();
  await step(page, 'burn'); await next(page); await step(page, 'exit');
  await page.getByRole('button', { name:'⤴ LEAVE TABLE', exact:true }).click();
  await step(page, 'complete');
  await expect(page.getByRole('region', { name:'Tutorial complete' })).toBeVisible();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('the-table/tutorial-v2')!).tutorialCompleted)).toBe(true);
  await page.screenshot({ path:'audit/screenshots/tutorial-complete.png' });
  await page.getByRole('button', { name:'PLAY TUTORIAL AGAIN', exact:true }).click(); await step(page,'look');
  expect(errors).toEqual([]);
});

test('resumes the saved chapter and allows hints to be disabled', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('the-table/tutorial-v2', JSON.stringify({ tutorialVersion:2, tutorialLastChapter:4, skippedForNow:true })));
  await page.goto('/'); await page.getByRole('button', { name:'RESUME TUTORIAL', exact:true }).click();
  await step(page,'downed');
  await page.getByRole('button', { name:'Save tutorial and return to menu' }).click();
  await page.getByRole('button', { name:'SETTINGS · AUDIO', exact:true }).click();
  await page.getByRole('button', { name:/First-time gameplay hints/ }).click();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('the-table/tutorial-v2')!).tutorialHintsDisabled)).toBe(true);
});
